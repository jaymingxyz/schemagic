<?php
/**
 * Generates includes/data/business-types.php from the official schema.org vocabulary.
 *
 * Usage:
 *   curl -L -o schemaorg.jsonld https://schema.org/version/latest/schemaorg-current-https.jsonld
 *   php bin/generate-business-types.php schemaorg.jsonld > includes/data/business-types.php
 *
 * Skips pending and retired types, and medical specialty enumerations that are
 * also modelled as classes (Dermatology, Pediatric, ...). Review labels for
 * acronyms and wording before committing the result.
 *
 * @package Schemagic
 */

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}

$path = isset( $argv[1] ) ? $argv[1] : '';

if ( '' === $path || ! is_readable( $path ) ) {
	fwrite( STDERR, "Usage: php bin/generate-business-types.php <schemaorg-current-https.jsonld>\n" );
	exit( 1 );
}

$json = json_decode( (string) file_get_contents( $path ), true );

if ( ! is_array( $json ) || empty( $json['@graph'] ) ) {
	fwrite( STDERR, "Could not read an @graph from {$path}\n" );
	exit( 1 );
}

$root     = 'LocalBusiness';
$parents  = array(); // type => parent types.
$children = array(); // type => child types.

foreach ( $json['@graph'] as $node ) {
	$types = isset( $node['@type'] ) ? (array) $node['@type'] : array();

	// Plain classes only: skip enumeration members that are also classes.
	if ( array( 'rdfs:Class' ) !== $types ) {
		continue;
	}

	if ( empty( $node['@id'] ) || 0 !== strpos( $node['@id'], 'schema:' ) ) {
		continue;
	}

	// Skip pending (pending.schema.org) and retired (attic.schema.org) types.
	if ( isset( $node['schema:isPartOf']['@id'] ) || isset( $node['schema:supersededBy'] ) ) {
		continue;
	}

	$type = substr( $node['@id'], 7 );

	if ( empty( $node['rdfs:subClassOf'] ) ) {
		continue;
	}

	$subclass_of = isset( $node['rdfs:subClassOf']['@id'] ) ? array( $node['rdfs:subClassOf'] ) : $node['rdfs:subClassOf'];

	foreach ( $subclass_of as $parent ) {
		if ( isset( $parent['@id'] ) && 0 === strpos( $parent['@id'], 'schema:' ) ) {
			$parent_type = substr( $parent['@id'], 7 );

			$parents[ $type ][]         = $parent_type;
			$children[ $parent_type ][] = $type;
		}
	}
}

// Breadth-first walk from LocalBusiness, recording each type's depth.
$depth = array( $root => 0 );
$queue = array( $root );

while ( $queue ) {
	$type = array_shift( $queue );

	foreach ( isset( $children[ $type ] ) ? $children[ $type ] : array() as $child ) {
		if ( ! isset( $depth[ $child ] ) ) {
			$depth[ $child ] = $depth[ $type ] + 1;
			$queue[]         = $child;
		}
	}
}

/**
 * "AutoBodyShop" => "Auto body shop", keeping acronyms like "HVAC".
 *
 * @param string $type Type name.
 * @return string
 */
function schemagic_label( $type ) {
	$words = preg_split( '/(?<=[a-z])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])/', $type );

	foreach ( $words as $i => $word ) {
		if ( strtoupper( $word ) !== $word ) {
			$words[ $i ] = 0 === $i ? ucfirst( strtolower( $word ) ) : strtolower( $word );
		}
	}

	return implode( ' ', $words );
}

$rows = array();

foreach ( $depth as $type => $level ) {
	$primary = '';

	if ( $type !== $root ) {
		// The deepest parent inside the tree is the most specific place to list the type.
		$best = -1;

		foreach ( $parents[ $type ] as $parent ) {
			if ( isset( $depth[ $parent ] ) && $depth[ $parent ] > $best ) {
				$best    = $depth[ $parent ];
				$primary = $parent;
			}
		}
	}

	$rows[ $type ] = array( schemagic_label( $type ), $primary );
}

ksort( $rows );
$rows = array( $root => $rows[ $root ] ) + $rows;

$width = max( array_map( 'strlen', array_keys( $rows ) ) ) + 2;

echo "<?php\n";
echo "/**\n";
echo " * Schema.org LocalBusiness subtypes: type => array( label, parent ).\n";
echo " *\n";
echo ' * Generated by bin/generate-business-types.php on ' . gmdate( 'Y-m-d' ) . ".\n";
echo " *\n";
echo " * @package Schemagic\n";
echo " */\n\n";
echo "defined( 'ABSPATH' ) || exit;\n\n";
echo "return array(\n";

foreach ( $rows as $type => $row ) {
	printf(
		"\t%s => array( __( '%s', 'schemagic' ), '%s' ),\n",
		str_pad( "'" . $type . "'", $width ),
		addcslashes( $row[0], "'\\" ),
		$row[1]
	);
}

echo ");\n";
